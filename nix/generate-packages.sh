#!/usr/bin/env bash
# =============================================
#   archenemy - nix/generate-packages.sh
#   Generuje nix/packages.nix (lista pakietów dla NixOS / home-manager,
#   EKSPERYMENTALNE, D10) z packages/platform-map.tsv. Jedno źródło prawdy:
#   ręcznie dopisany atrybut w packages.nix bez wiersza mapy pada w
#   tests/nix-packages.sh (`--check` + parser tekstowy).
#
#   Użycie:  bash nix/generate-packages.sh           → zapis nix/packages.nix
#            bash nix/generate-packages.sh --check   → 0 = plik aktualny, 1 = różni się
#            bash nix/generate-packages.sh --stdout  → treść na stdout
#
#   Reguły (raport C-D8-10/raport-D10.md, P1 D10):
#     - tylko wiersze nixos=ok; kolumna nix_attr to wtedy atrybuty nixpkgs
#       (jeden id → kilka, np. base-devel → gcc gnumake pkg-config);
#       wiersze system-managed (programs.*, services.*, hardware.*,
#       networking.*, boot.*, virtualisation.*) i „-” NIE trafiają do listy —
#       to opcje NixOS / home-manager, opisane w README;
#     - grupy: build = BUILD_ATTRS (kompilacja flux-wall), fonts = wiersze
#       z sondą font:, core = reszta list requirements-*, optional = listy
#       additional-* (zestaw nazwany: użytkownik wybiera pakiety jawnie);
#     - NIX_EXTRA = atrybuty spoza mapy, każdy z powodem (mapa opisuje
#       pakiety Archa; na Archu te pliki daje system bazowy);
#     - deduplikacja: atrybut zostaje przy pierwszym wystąpieniu;
#     - mapa to DANE: czytana `read`, nigdy eval/source; nieznana sekcja,
#       atrybut z niedozwolonymi znakami albo ścieżka opcji = błąd (kod 2).
#   Bez nix: ewaluacja i build listy są w D11/D12 (README „NixOS”).
# =============================================

set -uo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MAP="$REPO/packages/platform-map.tsv"
OUT="$REPO/nix/packages.nix"

# Przypięta, sprawdzona rewizja nixpkgs (raport D3, data commita z GitHub API).
NIXPKGS_REV="d5cc6833999746cffdfe0598f7bc801a57b887a9"
NIXPKGS_DATE="2026-11-13"

# Kompilacja src/flux-wall (Makefile: pkg-config wayland-client wayland-egl
# egl glesv2 libpulse-simple + wayland-scanner).
BUILD_ATTRS=(gcc gnumake pkg-config wayland wayland-scanner libGL libpulseaudio)

# Spoza mapy: grupa:atrybut — powód.
NIX_EXTRA=(
    "core:xkeyboard_config"   # evdev.lst dla scripts/hypr/keyboard-layouts.sh (nazwy i walidacja układów XKB)
    "build:zlib"              # make -C src/flux-wall tools (offscreen: -lz)
)

# Prefiksy opcji NixOS/HM — nigdy w liście pakietów.
OPTION_RE='^(programs|services|hardware|networking|boot|virtualisation|systemd|security|users|fonts|xdg|i18n|environment|nix|nixpkgs|home|wayland)\.'
ATTR_RE="^[A-Za-z_][A-Za-z0-9_'-]*(\.[A-Za-z_][A-Za-z0-9_'-]*)*$"

die() { echo "generate-packages.sh: $*" >&2; exit 2; }

declare -A SEEN=()
CORE=(); FONTS=(); BUILD=(); OPTIONAL=()

add() {
    local group="$1" attr="$2"
    [[ "$attr" =~ $ATTR_RE ]] || die "not a nixpkgs attribute: '$attr'"
    [[ "$attr" =~ $OPTION_RE ]] && die "NixOS/home-manager option in the package list: '$attr'"
    [[ -n "${SEEN[$attr]:-}" ]] && return 0
    SEEN[$attr]="$group"
    case "$group" in
        core) CORE+=("$attr") ;;
        fonts) FONTS+=("$attr") ;;
        build) BUILD+=("$attr") ;;
        optional) OPTIONAL+=("$attr") ;;
        *) die "unknown group '$group'" ;;
    esac
}

in_build() { local b; for b in "${BUILD_ATTRS[@]}"; do [[ "$b" == "$1" ]] && return 0; done; return 1; }

[[ -f "$MAP" ]] || die "missing $MAP"
section=""
while IFS= read -r line || [[ -n "$line" ]]; do
    if [[ "$line" =~ ^#\ ──\ ([A-Za-z0-9._-]+)\  ]]; then
        section="${BASH_REMATCH[1]}"; continue
    fi
    [[ "$line" =~ ^#\ ──\  ]] && { section="adhoc"; continue; }
    [[ -z "$line" || "$line" == \#* ]] && continue
    IFS=$'\t' read -r id _ _ _ _ nix_attr check _ status _ extra <<< "$line"
    [[ -n "${status:-}" && -z "${extra:-}" ]] || die "malformed map row: $id"
    [[ ";$status;" == *";nixos=ok;"* ]] || continue
    case "$section" in
        requirements-pacman.txt|requirements-aur.txt) kind=required ;;
        additional-packages-pacman.txt|additional-packages-aur.txt) kind=optional ;;
        *) die "nixos=ok row '$id' outside a package list section ('$section')" ;;
    esac
    [[ "$nix_attr" != "-" ]] || die "nixos=ok row '$id' without nixpkgs attribute"
    read -ra attrs <<< "$nix_attr"
    for a in "${attrs[@]}"; do
        if [[ "$kind" == optional ]]; then add optional "$a"
        elif in_build "$a"; then add build "$a"
        elif [[ "$check" == font:* ]]; then add fonts "$a"
        else add core "$a"
        fi
    done
done < "$MAP"
for e in "${NIX_EXTRA[@]}"; do add "${e%%:*}" "${e#*:}"; done

render() {
    local a
    cat <<EOF
# GENERATED by nix/generate-packages.sh from packages/platform-map.tsv — do not edit.
# Regenerate: bash nix/generate-packages.sh   (tests/nix-packages.sh checks it is current)
#
# archenemy packages for NixOS / home-manager — EXPERIMENTAL.
# Names checked against nixpkgs ${NIXPKGS_REV} (${NIXPKGS_DATE});
# not evaluated yet (planned in CI, see README "NixOS").
#
# This is only a package list. It does NOT enable Hyprland, the portal, PAM for
# hyprlock, audio (PipeWire), NetworkManager, Bluetooth or any other service:
# those are NixOS / home-manager options, see README "NixOS".
#
#   archenemy = import ./packages.nix { inherit pkgs; };
#   core     — what the desktop needs at runtime
#   fonts    — fonts the rices use (NixOS: fonts.packages)
#   build    — compiler and headers for src/flux-wall (use in a shell, see README)
#   optional — named set; pick packages explicitly, e.g. with archenemy.optional; [ btop mpv ]
{ pkgs }:
{
  core = [
EOF
    for a in "${CORE[@]}"; do printf '    pkgs.%s\n' "$a"; done
    printf '  ];\n  fonts = [\n'
    for a in "${FONTS[@]}"; do printf '    pkgs.%s\n' "$a"; done
    printf '  ];\n  build = [\n'
    for a in "${BUILD[@]}"; do printf '    pkgs.%s\n' "$a"; done
    printf '  ];\n  optional = {\n'
    for a in "${OPTIONAL[@]}"; do printf '    "%s" = pkgs.%s;\n' "$a" "$a"; done
    printf '  };\n}\n'
}

case "${1:-}" in
    --stdout) render ;;
    --check)
        [[ -f "$OUT" ]] || { echo "nix/packages.nix is missing — run: bash nix/generate-packages.sh" >&2; exit 1; }
        if [[ "$(render)" == "$(<"$OUT")" ]]; then exit 0; fi
        echo "nix/packages.nix is out of date — run: bash nix/generate-packages.sh" >&2
        exit 1 ;;
    "")
        tmp="$(mktemp "$OUT.XXXXXX")" || exit 2
        if render > "$tmp" && mv -f "$tmp" "$OUT"; then echo "written: nix/packages.nix"
        else rm -f "$tmp"; exit 2; fi ;;
    *) echo "usage: bash nix/generate-packages.sh [--check|--stdout]" >&2; exit 2 ;;
esac
