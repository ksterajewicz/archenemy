#!/usr/bin/env bash
# =============================================
#   archenemy - tests/install-main.sh
#   Główna ścieżka install.sh od początku do końca (audyt 2026-11-05, T6/KT3).
#   Pozostałe testy instalatora wycinają pojedyncze kroki sedem
#   (machine-layer.sh, install-link.sh, install-summary.sh), więc błąd na
#   styku kroków albo w krokach [7]–[10] nie dawał czerwieni. Tu biegnie
#   cały prawdziwy install/install.sh:
#     - z kopii repo w tymczasowym $HOME/archenemy (pliki z gita + nowe,
#       bez ignorowanych; trzy skrypty bez bitu x, żeby [9.5] miał co zrobić;
#       kopia dostaje własny commit dla installed-head.dat),
#     - w terminalu (pty, tests/lib/drive-pty.py odpowiada na pytania według
#       listy; pytanie spoza listy albo zawieszenie = porażka),
#     - na atrapach w PATH: sudo, pacman, yay, systemctl, hyprctl
#       (tests/mock/hyprctl), ufw, powerprofilesctl, lspci, narzędzia budowania
#       flux-walla, python3 (generator tapet), pkill/pgrep/hyprpaper,
#     - z ARCHENEMY_TEST=1.
#   Sprawdza skutki (pliki, symlinki, wywołania atrap), nie same komunikaty.
#   Drugi bieg (zalecany po każdym pullu) ma nie zmienić żadnego pliku.
#   EUID nie da się podrobić: na VPS i w CI (root) kopia instalatora dostaje
#   wyłączony strażnik roota — test sprawdza, że to jedyna różnica, a sam
#   strażnik ma własny test (tests/install-guards.sh, K8).
#   Bez roota, bez sieci, bez zapisu poza mktemp.
#   Uruchom: bash tests/install-main.sh   (kod 0 = wszystko przeszło)
# =============================================

# shellcheck disable=SC2016,SC2034  # check() robi eval na cytowanym wyrażeniu (zmienne żyją w eval)
set -uo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=tests/lib/environment.sh
source "$REPO/tests/lib/environment.sh"
PY="$(command -v python3 || command -v python || true)"
if [[ -z "$PY" ]]; then echo "brak pythona (sterowanie pty) — pomijam"; exit 0; fi
LUA="$(command -v lua5.4 || command -v lua || true)"
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
test_environment_init "$T" || exit 1
# Świeży system po pierwszym starcie Hyprlanda: ~/.config istnieje, a w nim
# config wygenerowany przez Hyprland (prawdziwy katalog, nie link).
mkdir -p "$HOME/.config/hypr" && echo "# autogenerated = 1" > "$HOME/.config/hypr/hyprland.conf"

PASS=0; FAIL=0
ok()   { PASS=$((PASS + 1)); echo "  ✓ $1"; }
fail() { FAIL=$((FAIL + 1)); echo "  ✗ $1"; }
check() { if eval "$2"; then ok "$1"; else fail "$1"; fi; }

# ─── kopia repo w $HOME/archenemy ─────────────────────────────────────────────
A="$HOME/archenemy"
mkdir -p "$A"
if git -C "$REPO" rev-parse --git-dir >/dev/null 2>&1; then
    # Śledzone i nowe pliki drzewa roboczego (bez ignorowanych: data/, pliki
    # generowane maszyny) — usunięte z drzewa pomija `[[ -e ]]`.
    while IFS= read -r -d '' f; do
        [[ -e "$REPO/$f" || -L "$REPO/$f" ]] && printf '%s\0' "$f"
    done < <(git -C "$REPO" ls-files -z -co --exclude-standard) \
        | (cd "$REPO" && xargs -0 cp -a --parents -t "$A")
else
    cp -a "$REPO/." "$A/"
    rm -rf "$A/.git" "$A/data" "$A/.current_rice" "$A/backups"
fi
# [9.5] nadaje skryptom bit x, a cp -a przenosi go z gita (wszystkie mają
# 100755), więc bez tego sprawdzenie po biegu 1 nie mogło paść (przegląd
# P-4). Trzy skrypty bez bitu, zanim kopia dostanie commit — dwa z
# scripts/<katalog>/ i jeden głębiej (find w [9.5] musi zejść rekurencyjnie).
mapfile -t NOEXEC_PRE < <(find "$A/scripts" -mindepth 2 -maxdepth 2 -name '*.sh' | LC_ALL=C sort | head -2
                          find "$A/scripts" -mindepth 3 -name '*.sh' | LC_ALL=C sort | head -1)
chmod -x "${NOEXEC_PRE[@]}"
check "kopia: 3 skrypty bez bitu x przed biegiem 1" '[[ ${#NOEXEC_PRE[@]} -eq 3 && -z "$(find "${NOEXEC_PRE[@]}" -perm -u+x)" ]]'
INST="$A/install/install.sh"
if [[ $EUID -eq 0 ]]; then
    sed -i 's/^if \[\[ \$EUID -eq 0 \]\]; then$/if false; then  # tests\/install-main.sh: bieg jako root w atrapie/' "$INST"
    check "root: w kopii wyłączony tylko strażnik roota" '[[ "$(diff "$REPO/install/install.sh" "$INST" | grep -c "^[<>]")" -eq 2 ]]'
fi
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
GIT=(git -C "$A" -c user.name=test -c user.email=test@example.invalid -c commit.gpgsign=false -c core.hooksPath=/dev/null)
if ! { "${GIT[@]}" init -q && "${GIT[@]}" add -A && "${GIT[@]}" commit -qm "atrapa repo"; }; then
    echo "  ✗ nie udało się przygotować kopii repo"; exit 1
fi
COPY_HEAD="$("${GIT[@]}" rev-parse HEAD)"

# ─── atrapy ──────────────────────────────────────────────────────────────────
# Każda atrapa dopisuje wywołanie do $MOCK_LOG; stan usług, pakietów i zapory
# leży w $MOCK_STATE (poza $HOME, więc nie wchodzi do porównania biegów).
export MOCK_LOG="$T/log" MOCK_STATE="$T/state" MOCK_MONS=both
export MOCK_HYPRPAPER_STATE="$MOCK_STATE/hyprpaper" MOCK_HYPRCTL="$REPO/tests/mock/hyprctl"
mkdir -p "$T/bin" "$MOCK_STATE"
: > "$MOCK_HYPRPAPER_STATE"   # plik istnieje = demon hyprpapera działa
stub() { printf '#!/usr/bin/env bash\n%s\n' "$2" > "$T/bin/$1"; chmod +x "$T/bin/$1"; }
stub sudo 'echo "sudo $*" >> "$MOCK_LOG"; [[ "$1" == -k ]] && exit 0; exec "$@"'
# pacman: -Qi = zainstalowany, chyba że nazwa jest w $MOCK_STATE/pacman-missing;
# -S „instaluje” (usuwa nazwy z listy brakujących).
stub pacman 'echo "pacman $*" >> "$MOCK_LOG"
m="$MOCK_STATE/pacman-missing"; touch "$m"
case "$1" in
  -Qi) ! grep -qxF -- "$2" "$m" ;;
  -S)  for a in "${@:2}"; do [[ "$a" == -* ]] || sed -i "/^${a}\$/d" "$m"; done; exit 0 ;;
esac'
stub yay 'echo "yay $*" >> "$MOCK_LOG"'
# systemctl: stan jednostek w $MOCK_STATE/systemd/<system|user>/<nazwa>.{enabled,active}
stub systemctl 'echo "systemctl $*" >> "$MOCK_LOG"
scope=system; args=(); now=0
for a in "$@"; do case "$a" in --user) scope=user ;; --quiet|-q) ;; --now) now=1 ;; *) args+=("$a") ;; esac; done
d="$MOCK_STATE/systemd/$scope"; mkdir -p "$d"
cmd="${args[0]:-}"; units=("${args[@]:1}"); units=("${units[@]%.service}")
case "$cmd" in
  is-enabled) [[ -e "$d/${units[0]}.enabled" ]] ;;
  is-active)  [[ -e "$d/${units[0]}.active" ]] ;;
  enable)     for u in "${units[@]}"; do : > "$d/$u.enabled"; (( now )) && : > "$d/$u.active"; done; exit 0 ;;
  start)      for u in "${units[@]}"; do : > "$d/$u.active"; done ;;
esac'
# ufw: stan w $MOCK_STATE/ufw.*; `default` zapisuje politykę jak prawdziwy.
stub ufw 'echo "ufw $*" >> "$MOCK_LOG"
s="$MOCK_STATE/ufw"
case "$1" in
  status)  if [[ -e "$s.active" ]]; then echo "Status: active"
           [[ "${2:-}" == verbose ]] && printf "Logging: on (low)\nDefault: %s (incoming), %s (outgoing), disabled (routed)\nNew profiles: skip\n" "$(cat "$s.in" 2>/dev/null || echo deny)" "$(cat "$s.out" 2>/dev/null || echo allow)"
           else echo "Status: inactive"; fi ;;
  default) [[ "$3" == incoming ]] && echo "$2" > "$s.in"; [[ "$3" == outgoing ]] && echo "$2" > "$s.out" ;;
  enable)  : > "$s.active"; echo "Firewall is active and enabled on system startup" ;;
esac
exit 0'
stub hyprctl 'echo "hyprctl $*" >> "$MOCK_LOG"; [[ "$1" == reload ]] && { echo ok; exit 0; }; exec "$MOCK_HYPRCTL" "$@"'
stub powerprofilesctl '[[ "$1" == get ]] && echo balanced; true'
stub lspci 'echo "03:00.0 VGA compatible controller: Advanced Micro Devices, Inc. [AMD/ATI] Navi 24"'
for t in gcc wayland-scanner pkg-config mpd ncmpcpp clear notify-send hyprpaper waybar pkill; do stub "$t" 'true'; done
stub pgrep 'exit 1'
stub make 'echo "make $*" >> "$MOCK_LOG"; [[ "$1" == -C ]] && mkdir -p "$2/build" && printf "#!/bin/sh\n" > "$2/build/flux-wall" && chmod +x "$2/build/flux-wall"'
stub python3 'echo "python3 $*" >> "$MOCK_LOG"'
export PATH="$T/bin:$PATH" TERM=dumb ARCHENEMY_TEST=1

# run_install <plik odpowiedzi> <przyrostek> — bieg w pty; transkrypcja w
# $T/out.<p>, zadane pytania w $T/asked.<p>, wywołania atrap w $T/log.<p>.
run_install() {
    : > "$MOCK_LOG"
    (cd "$HOME" && "$PY" "$REPO/tests/lib/drive-pty.py" "$1" "$T/out.$2" "$T/asked.$2" bash "$INST")
    RC=$?
    cp "$MOCK_LOG" "$T/log.$2"
    OUT="$(<"$T/out.$2")"; ASKED="$(<"$T/asked.$2")"; LOG="$(<"$T/log.$2")"
}
asked() { grep -qE -- "$1" <<< "$ASKED"; }
called() { grep -qxE -- "$1" <<< "$LOG"; }
# Migawka plików w $HOME (typ, prawa, treść albo cel linku) — do porównania
# biegów. Poza porównaniem: .git kopii, installed-head.dat (data biegu)
# i hyprlock-wallpaper.dat — przełącznik tapet zapisuje go przy --restore
# (bieg 2) z wartością domyślną „off”, sprawdzaną niżej osobno.
snapshot() {
    (cd "$HOME" && find . \( -path ./archenemy/.git -o -path ./archenemy/data/installed-head.dat \
                -o -path ./archenemy/data/hyprlock-wallpaper.dat \) -prune -o -printf '%p %y %m %l\n' | sort
     find . \( -path ./archenemy/.git -o -path ./archenemy/data/installed-head.dat \
                -o -path ./archenemy/data/hyprlock-wallpaper.dat \) -prune -o -type f -print0 \
         | xargs -0 sha256sum | sort -k2)
}

# Odpowiedzi: wzorzec (regex na koniec wiersza pytania) <TAB> odpowiedź.
# Pusta odpowiedź = Enter (wartość domyślna).
ANS="$T/answers"
cat > "$ANS" <<'EOF'
Resolution \[[^]]*\]:
Refresh rate in Hz \[[^]]*\]:
Position XxY \[[^]]*\]:
Scale \[[^]]*\]:
Role \(primary/secondary/other\) \[[^]]*\]:
Enter = confirm, or enter your own order.*:
Choose mode \[1/2\]:	1
Install missing pacman packages\? \[Y/n\]:
Would you like to install additional useful packages\? \[y/N\]:	n
Select your device \[default: [0-9]\]:	3
Run CPU microcode installer\? \[y/N\]:	n
Run GPU drivers installer\? \[y/N\]:	n
Run kernel installer\? \[y/N\]:	n
^\[y/N\]:	n
Enable mpd as your user service now.*\[y/N\]:	y
Add the 'archenemy' command.*\[Y/n\]:
UFW.*\[y/N\]:	y
Enable NetworkManager.*\[Y/n\]:
Set up Bluetooth.*\[y/N\]:	n
Install Oracle VirtualBox.*\[y/N\]:	n
Reload Hyprland now\? \[y/N\]:	y
EOF

echo "== bieg 1: świeża instalacja (2 monitory, brakuje jednego pakietu)"
echo swayosd > "$MOCK_STATE/pacman-missing"
run_install "$ANS" 1
H="$A/config/hypr"
check "kod 0, bez zawieszenia i pytań spoza listy" '[[ $RC -eq 0 ]]'
check "doszedł do końca (pytanie o reload)"   'asked "Reload Hyprland now"'
check "[3.7] data/monitors/*.dat i tryb shared" '[[ -f "$A/data/monitors/eDP-1.dat" && -f "$A/data/monitors/HDMI-A-3.dat" && "$(<"$A/data/workspace-mode.dat")" == shared ]]'
check "[3.5] role z kolejności hyprctl: primary + secondary" 'grep -qx "ROLE=primary" "$A/data/monitors/HDMI-A-3.dat" && grep -qx "ROLE=secondary" "$A/data/monitors/eDP-1.dat"'
check "[5] brakujący pakiet doinstalowany pacmanem" 'called "pacman -S --needed swayosd"'
check "[6] profil universal, ppd włączony"     '[[ "$(<"$A/data/hardware.dat")" == universal ]] && called "systemctl enable --now power-profiles-daemon"'
check "[8a] monitorshyprl.lua: oba monitory po desc:" '[[ "$(grep -c "^hl.monitor({ output = \"desc:" "$H/monitorshyprl.lua")" -eq 2 ]]'
check "[8] gpu-env.lua z lspci (amd), hardware-keys.lua" 'grep -q "GPU: amd" "$H/gpu-env.lua" && grep -q "universal" "$H/hardware-keys.lua"'
missing=""
for f in monitorshyprl.lua workspaces-monitors.lua hardware-keys.lua gpu-env.lua autostartpersonalisation.lua \
         appbinds.lua autostart-apps.lua hyprpaper.conf hyprlock-background-{white-blue,tron,asia-n-rice,dither-flux,crt,yin}.conf; do
    [[ -s "$H/$f" ]] || missing+=" $f"
done
check "[8] każdy plik warstwy maszynowej istnieje${missing:+ (brak:$missing)}" '[[ -z "$missing" ]]'
check "[8l] ~/.config/mpd → config/mpd, output.conf (pipewire)" '[[ "$(readlink "$HOME/.config/mpd")" == "$A/config/mpd" ]] && grep -q "type.*\"pipewire\"" "$A/config/mpd/output.conf"'
check "[8l] usługa użytkownika mpd włączona po y" 'called "systemctl --user enable --now mpd.service"'
check "[8l] ncmpcpp.desktop skopiowany"        'cmp -s "$A/config/applications/ncmpcpp.desktop" "$HOME/.local/share/applications/ncmpcpp.desktop"'
check "[8m] archenemy.desktop wskazuje kopię repo" 'grep -qF "Exec=alacritty --class archenemy-appbinds -e \"$A/scripts/appbinds/appbinds.sh\"" "$HOME/.local/share/applications/archenemy.desktop"'
check "[8m] ~/.bashrc z blokiem archenemy, alias dodany" 'grep -qxF "# >>> archenemy shell >>>" "$HOME/.bashrc" && grep -q "^alias archenemy=" "$A/config/shell/shellrc"'
links_bad=""
for src in "$A/rices/white-blue"/*/; do
    n="$(basename "$src")"
    [[ "$(readlink "$HOME/.config/$n")" == "${src%/}" ]] || links_bad+=" $n"
done
check "[9] każdy folder white-blue podlinkowany w ~/.config${links_bad:+ (źle:$links_bad)}" '[[ -z "$links_bad" ]]'
check "[9] config Hyprlanda odłożony do .bak, nie skasowany" 'grep -qx "# autogenerated = 1" "$HOME"/.config/hypr.bak-*/hyprland.conf && [[ "$OUT" == *"Your previous ~/.config/hypr was kept as hypr.bak-"* ]]'
noexec="$(find "$A/scripts" -name '*.sh' ! -perm -u+x | head -3)"
check "[9.5] skrypty wykonywalne (też 3 bez bitu przed biegiem), ~/Screenshots" '[[ -z "$noexec" && -d "$HOME/Screenshots" ]]'
check "[9.5] tapeta wysłana do obu monitorów (IPC)" '[[ "$(grep -c . "$MOCK_HYPRPAPER_STATE")" -eq 2 ]] && [[ "$OUT" == *"Initial wallpaper applied"* ]]'
check "[9.6] flux-wall zbudowany make -C src/flux-wall" 'called "make -C $A/src/flux-wall" && [[ -x "$A/src/flux-wall/build/flux-wall" ]]'
check "[9.7] generator tapet: v1 1920x1080, v2 2560x1600" 'grep -qE "^python3 .*/gen_dither_flux_wallpaper.py .* (v1:1920x1080 v2:2560x1600|v2:2560x1600 v1:1920x1080)$" "$T/log.1"'
check "[10] ufw: polityki, enable, usługa"     'called "ufw default deny incoming" && called "ufw enable" && called "systemctl enable ufw"'
check "[10] pytanie o ufw mówi, co włączenie zmienia" '[[ "$OUT" == *"blocks incoming connections"* && "$OUT" == *"rp_filter"* && "$OUT" == *"Remote Play"* ]] && asked "UFW.*\[y/N\]"'
check "[10] NetworkManager i pipewire-pulse włączone" 'called "systemctl enable --now NetworkManager" && called "systemctl --user enable --now pipewire.socket pipewire-pulse.socket wireplumber.service"'
check "[11] installed-head.dat = HEAD kopii"   '[[ "$(sed -n "s/^COMMIT=//p" "$A/data/installed-head.dat")" == "$COPY_HEAD" ]]'
check "[11] baner pełnego sukcesu, jedyny czerwony wiersz = brakujący pakiet" '[[ "$OUT" == *"Everything is set up. Have fun!"* && "$(grep "✗" <<< "$OUT")" == "  ✗ missing: swayosd" ]]'
check "[11] sudo -k po ostatnim sudo, reload ok" '[[ "$(grep "^sudo" "$T/log.1" | tail -1)" == "sudo -k" ]] && [[ "$OUT" == *"Hyprland reloaded"* ]]'
check "machine-layer-check.sh: warstwa maszynowa spójna" 'bash "$A/scripts/hypr/machine-layer-check.sh" --quiet </dev/null >/dev/null 2>&1'
# Config rice'a z ~/.config/hypr wykonany na atrapie hl: każdy require musi
# trafić w istniejący plik (atrapa require NIE wybacza braku) i dać się wykonać.
if [[ -n "$LUA" ]]; then
    cat > "$T/hl.lua" <<'EOF'
local function proxy()
    return setmetatable({}, { __index = function() return proxy() end, __call = function() return proxy() end })
end
hl = proxy()
require = function(path) assert(io.open(path, "r"), "brak pliku: " .. path):close(); dofile(path) end
dofile(arg[1])
EOF
    lua_err="$("$LUA" "$T/hl.lua" "$HOME/.config/hypr/hyprland.lua" 2>&1)"
    check "hyprland.lua rice'a wykonuje się z wygenerowanymi plikami${lua_err:+: ${lua_err##*$'\n'}}" '[[ -z "$lua_err" ]]'
else
    echo "  - pominięte: brak lua5.4 (wykonanie hyprland.lua)"
fi

echo "== bieg 2: ponowny bieg (Enter = zostaw) nie zmienia plików"
snapshot > "$T/snap.1"
# Użytkownik po biegu 1 zaostrzył zaporę (ufw default deny outgoing); lista
# odpowiedzi nadal ma „y” dla ufw — ponowny bieg nie może ruszyć polityk (S7).
echo deny > "$MOCK_STATE/ufw.out"
# …i sam włączył mpd.socket (aktywacja gniazdem: port 6600 na wszystkich
# interfejsach, bind_to_address pomijany) — ma usłyszeć to wprost (S13).
: > "$MOCK_STATE/systemd/user/mpd.socket.enabled"
run_install "$ANS" 2
snapshot > "$T/snap.2"
check "kod 0, bez zawieszenia i pytań spoza listy" '[[ $RC -eq 0 ]]'
check "pliki w \$HOME bez zmian względem biegu 1" 'diff -q "$T/snap.1" "$T/snap.2" >/dev/null'
diff "$T/snap.1" "$T/snap.2" | head -10 | sed 's/^/      /'
check "nie pyta o rzeczy już zrobione (mpd, alias, NetworkManager)" '! asked "Enable mpd as your user service" && ! asked "archenemy. command" && ! asked "Enable NetworkManager"'
check "[9.5] tapeta odtworzona, nie nadpisana"  '[[ "$OUT" == *"Wallpaper kept"* ]]'
check "[10] aktywny ufw: bez pytania, polityki nietknięte (S7)" '! asked "UFW" && ! grep -q "^ufw default" "$T/log.2" && [[ "$(<"$MOCK_STATE/ufw.out")" == deny ]]'
check "[10] aktywny ufw: komunikat z obecnymi politykami" '[[ "$OUT" == *"UFW firewall already active"* && "$OUT" == *"deny (incoming), deny (outgoing)"* ]]'
check "[8l] mpd.socket: ostrzeżenie o porcie 6600 zamiast 'already enabled' (S13)" '[[ "$OUT" == *"mpd.socket (user) is enabled"* && "$OUT" == *"ignores bind_to_address"* && "$OUT" != *"mpd user service already enabled"* ]]'
check "[8l] mpd.socket: wpis w podsumowaniu z komendą, bez zmiany usług" '[[ "$OUT" == *"skipped: mpd.socket listens on port 6600"*"systemctl --user disable --now mpd.socket"* ]] && ! grep -q "^systemctl --user \(enable\|disable\)" "$T/log.2"'
check "[5] nic nie doinstalowuje"               '! grep -q "^pacman -S --needed swayosd" "$T/log.2"'
check "hyprlock-wallpaper.dat (jeśli powstał) = off" '[[ ! -e "$A/data/hyprlock-wallpaper.dat" || "$(<"$A/data/hyprlock-wallpaper.dat")" == off ]]'

echo ""
echo "Wynik: $PASS ✓ / $FAIL ✗"
[[ $FAIL -eq 0 ]]
