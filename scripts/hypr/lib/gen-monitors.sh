#!/usr/bin/env bash
# =============================================
#   archenemy - lib/gen-monitors.sh
#   Generator config/hypr/monitorshyprl.lua z data/monitors/*.dat.
#   JEDNO ŹRÓDŁO PRAWDY — source'owane przez install/install.sh (krok 8a),
#   scripts/hypr/monitor-settings.sh (zmiana na żywo, Super+A → [n])
#   i workspace-mode-switch.sh (kolejność monitorów).
#   Nie uruchamiaj bezpośrednio — to biblioteka funkcji.
#   Wymaga: monitor_selector_from_dat i lua_string z lib/monitor-id.sh.
# =============================================

# Jedna wartość z pliku .dat monitora.
monitor_dat_get() {
    grep -m1 "^$2=" "$1" 2>/dev/null | cut -d= -f2-
}

# Pliki .dat wg numeru monitora (ORDER), po jednym w linii.
monitor_dats_sorted() {
    local dir="$1" f
    for f in "$dir"/*.dat; do
        [[ -e "$f" ]] || continue
        printf '%s\t%s\n' "$(monitor_dat_get "$f" ORDER)" "$f"
    done | sort -n -s -k1,1 | cut -f2-
}

# Wejście generatora workspace'ów: "<nazwa pliku .dat><TAB><selektor>" wg ORDER.
# Klucz to nazwa PLIKU, bo jest unikalna: dwa .dat mogą mieć to samo MONITOR=
# (odpięty monitor i nowy na tym samym złączu). Plik bez ORDER pomijamy.
monitor_entries_ordered() {
    local f
    while IFS= read -r f; do
        [[ -n "$(monitor_dat_get "$f" ORDER)" ]] || continue
        printf '%s\t%s\n' "$(basename "$f" .dat)" "$(monitor_selector_from_dat "$f")"
    done < <(monitor_dats_sorted "$1")
}

# Argumenty: <plik-wyjściowy .lua> <katalog data/monitors>. Zapis atomowy.
# output = selektor "desc:<opis>" (lib/monitor-id.sh), nie nazwa złącza — nazwa
# zmienia się po restarcie i reguła przestawała pasować (2026-09-21).
generate_monitors_conf() {
    local out="$1" dir="$2" tmp f mon res rate pos scale sel
    tmp="$(mktemp "${out}.XXXXXX")" || return 1
    {
        echo "-- generated by archenemy install.sh"
        echo "-- Monitors (output = desc:<opis EDID>; nazwa złącza w komentarzu = stan z dnia instalacji)"
        while IFS= read -r f; do
            mon="$(basename "$f" .dat)"
            res="$(monitor_dat_get "$f" RESOLUTION)"
            rate="$(monitor_dat_get "$f" RATE)"
            pos="$(monitor_dat_get "$f" POSITION)"
            scale="$(monitor_dat_get "$f" SCALE)"
            sel="$(lua_string "$(monitor_selector_from_dat "$f")")"

            echo "-- $mon"
            if [[ -n "$rate" ]]; then
                echo "hl.monitor({ output = $sel, mode = \"${res}@${rate}\", position = \"$pos\", scale = $scale })"
            else
                echo "hl.monitor({ output = $sel, mode = \"$res\", position = \"$pos\", scale = $scale })"
            fi
        done < <(monitor_dats_sorted "$dir")
        # Pusty output = reguła fallback dla monitorów bez własnej reguły.
        echo "hl.monitor({ output = \"\", mode = \"preferred\", position = \"auto\", scale = 1 })"
    } > "$tmp"
    chmod 644 "$tmp"   # mktemp daje 600 — jak pozostałe pliki warstwy maszynowej
    mv "$tmp" "$out"
}
