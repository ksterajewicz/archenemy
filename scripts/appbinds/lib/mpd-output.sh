#!/bin/bash
# =============================================
#   archenemy - scripts/appbinds/lib/mpd-output.sh
#   Wyjście audio mpd (pipewire / alsa) dla TUI Super+A. Source'owana przez
#   appbinds.sh i tests/mpd-output.sh, bez efektów ubocznych przy wczytaniu.
#   Wymaga: $ARCHENEMY_DIR i write_dat (lib/tui.sh albo appbinds.sh).
#
#   Pipewire jest ZALECANE (miksuje się z pulpitem, klawisze głośności działają,
#   tapety ♪ flux-walla słyszą muzykę). ALSA `hw:` to tryb WYŁĄCZNY: dopóki mpd
#   trzyma kartę, reszta pulpitu może stracić dźwięk. Ten kod NIGDY nie zatrzymuje
#   pipewire/wireplumbera.
#
#   Mechanizm: config/mpd/output.conf (warstwa maszynowa, `include` z mpd.conf)
#   + restart usługi użytkownika. `mpc enable/disable` nie wystarczy: state_file
#   mpd (src/output/State.cxx) przy odczycie tylko WYŁĄCZA wyjścia, więc wybór
#   nie przeżyłby restartu.
#
#   Test po przełączeniu (audyt TUI 2026-11-05, A1–A3): mpd otwiera wyjście
#   dopiero przy graniu, a MultipleOutputs::Open zgłasza błąd tylko wtedy, gdy
#   nie otworzy się ŻADNE wyjście (MPD 0.24, src/output/MultipleOutputs.cxx).
#   Wyjście fifo wizualizera otwiera się zawsze, więc przy włączonym fifo awaria
#   ALSA/PipeWire daje ciszę bez `ERROR:` w `mpc status`. Na czas testu fifo
#   jest wyłączone; włączamy je z powrotem zawsze, także po porażce.
# =============================================

MPD_OUTPUT_CONF="$ARCHENEMY_DIR/config/mpd/output.conf"
MPD_OUTPUT_DAT="$ARCHENEMY_DIR/data/mpd-output.dat"
MPD_FIFO_OUTPUT="Visualizer feed"
# Katalog /proc/asound — zmienna tylko po to, żeby testy mogły go podmienić.
ASOUND_DIR="${ARCHENEMY_ASOUND_DIR:-/proc/asound}"

# Wypisz urządzenia PCM do odtwarzania z /proc/asound (bez alsa-utils):
# linie "hw:C,D<TAB>nazwa karty — nazwa PCM". /proc/asound/pcm ma format
# "CC-DD: nazwa : typ : playback N : capture N".
list_alsa_playback() {
    [[ -r "$ASOUND_DIR/pcm" ]] || return 1
    local line card dev name cardname
    while IFS= read -r line; do
        [[ "$line" == *"playback"* ]] || continue
        card="${line%%-*}"; card="$((10#$card))"
        dev="${line#*-}"; dev="${dev%%:*}"; dev="$((10#$dev))"
        name="${line#*: }"; name="${name%% :*}"
        cardname="$(sed -n "s/^ *$card \[[^]]*\]: [^ ]* - //p" "$ASOUND_DIR/cards" 2>/dev/null | head -1)"
        printf 'hw:%s,%s\t%s — %s\n' "$card" "$dev" "${cardname:-card $card}" "$name"
    done < "$ASOUND_DIR/pcm"
}

# Czy urządzenie hw:C,D jest teraz otwarte przez kogoś (np. pipewire)?
# /proc/asound/cardC/pcmDp/sub0/status = "closed", gdy wolne. Brak pliku =
# nie wiemy (traktuj jak wolne, test odtwarzania i tak to zweryfikuje).
alsa_device_busy() {
    local hw="$1" card dev f
    card="${hw#hw:}"; card="${card%%,*}"; dev="${hw##*,}"
    f="$ASOUND_DIR/card$card/pcm${dev}p/sub0/status"
    [[ -r "$f" ]] || return 1
    ! grep -qx 'closed' "$f"
}

# Nazwa wyjścia w mpd dla trybu: ta sama trafia do output.conf i `mpc outputs`.
mpd_output_name() {
    if [[ "$1" == "alsa" ]]; then printf 'ALSA %s' "$2"; else printf 'PipeWire'; fi
}

# Czy zmiana output.conf w ogóle dotrze do mpd. Kod 0 = tak; inaczej powód na
# stdout. [8l] celowo zostawia cudzą konfigurację bez linku, a mpd czyta wtedy
# swój plik, więc zapis tutaj niczego by nie zmienił.
mpd_output_blocker() {
    local conf="${XDG_CONFIG_HOME:-$HOME/.config}/mpd"
    if [[ "$(readlink -f "$conf" 2>/dev/null)" != "$(readlink -f "$ARCHENEMY_DIR/config/mpd" 2>/dev/null)" ]]; then
        echo "mpd does not read archenemy's config: $conf is not linked to config/mpd (installer step [8l])."
        return 1
    fi
    if systemctl is-active --quiet mpd.service 2>/dev/null; then
        echo "mpd runs as a system service, so this menu cannot restart it (system config: /etc/mpd.conf)."
        return 1
    fi
    return 0
}

# Zapisz output.conf i .dat razem (atomowo), żeby stan pliku i menu nie rozjechał
# się nawet po podwójnej porażce.
write_mpd_output_conf() {
    local mode="$1" hw="${2:-}" tmp name
    name="$(mpd_output_name "$mode" "$hw")"
    mkdir -p "$(dirname "$MPD_OUTPUT_CONF")"
    tmp="$(mktemp "${MPD_OUTPUT_CONF}.XXXXXX")" || return 1
    {
        echo "# generated by archenemy (Super+A → [o] → 3) — wyjście audio mpd (warstwa maszynowa)."
        echo "# pipewire zalecane; alsa = tryb wylaczny (patrz README, sekcja Music stack)."
        echo "audio_output {"
        if [[ "$mode" == "alsa" ]]; then
            echo "    type        \"alsa\""
            echo "    name        \"$name\""
            echo "    device      \"$hw\""
            # software: mpd NIE kręci gałką sprzętową pod pipewire — inaczej
            # poziom karty zmieniałby się „sam” po powrocie na pipewire.
            echo "    mixer_type  \"software\""
        else
            echo "    type  \"pipewire\""
            echo "    name  \"$name\""
        fi
        echo "}"
    } > "$tmp"
    mv "$tmp" "$MPD_OUTPUT_CONF"
    write_dat "$MPD_OUTPUT_DAT" "$mode${hw:+ $hw}"
}

# Restart mpd i czekanie, aż odpowie. Kod 1 = nie wstał.
restart_mpd_and_wait() {
    systemctl --user restart mpd.service 2>/dev/null || return 1
    local _i
    for _i in $(seq 1 25); do
        mpc status >/dev/null 2>&1 && return 0
        sleep 0.2
    done
    return 1
}

# Stan odtwarzania: playing / paused / stopped.
mpd_play_state() {
    local status
    status="$(mpc status 2>/dev/null)"
    case "$status" in
        *'[playing]'*) echo playing ;;
        *'[paused]'*)  echo paused ;;
        *)             echo stopped ;;
    esac
}

# Sekundowe odtwarzanie na samym wyjściu głównym. Kod 0 = gra, 1 = awaria
# (treść na stdout). Wołający przywraca stan odtwarzania.
mpd_play_test() {
    local err="" state
    mpc disable "$MPD_FIFO_OUTPUT" >/dev/null 2>&1
    mpc clearerror >/dev/null 2>&1
    mpc play >/dev/null 2>&1
    sleep 1
    err="$(mpc status 2>&1 | sed -n 's/^ERROR: //p' | head -1)"
    state="$(mpd_play_state)"
    mpc enable "$MPD_FIFO_OUTPUT" >/dev/null 2>&1
    if [[ -n "$err" ]]; then
        mpc clearerror >/dev/null 2>&1
        echo "$err"
        return 1
    fi
    [[ "$state" == "playing" ]] && return 0
    echo "playback did not start"
    return 1
}

mpd_restore_state() {
    case "$1" in
        playing) ;;
        paused)  mpc pause >/dev/null 2>&1 ;;
        *)       mpc stop >/dev/null 2>&1 ;;
    esac
}

# Zastosuj tryb: zapis, restart, sprawdzenie wyjścia, test odtwarzania.
# Kody: 0 = gra, 1 = awaria (wołający robi powrót), 3 = zapisane, ale niesprawdzone
# (pusta kolejka, nie ma czym zagrać). Powód porażki idzie na stdout.
apply_mpd_output() {
    local mode="$1" hw="${2:-}" name state rc=0 msg=""
    name="$(mpd_output_name "$mode" "$hw")"
    state="$(mpd_play_state)"
    write_mpd_output_conf "$mode" "$hw" || { echo "cannot write $MPD_OUTPUT_CONF"; return 1; }
    restart_mpd_and_wait || { echo "mpd did not come back after restart (journalctl --user -u mpd)"; return 1; }

    # state_file mógł wyłączyć wyjście o tej nazwie; brak na liście = mpd czyta inny config.
    if ! mpc outputs 2>/dev/null | grep -Fq "($name) is "; then
        echo "mpd does not list output '$name'"
        return 1
    fi
    mpc enable "$name" >/dev/null 2>&1

    [[ -n "$(mpc playlist 2>/dev/null | head -1)" ]] || return 3

    msg="$(mpd_play_test)" || rc=1
    mpd_restore_state "$state"
    [[ -n "$msg" ]] && echo "$msg"
    return "$rc"
}

# Wyjście, które mpd ma teraz włączone (bez fifo wizualizera). Gdy mpd nie
# odpowiada: ostatni zapisany wybór z dopiskiem.
mpd_current_output() {
    local name
    name="$(mpc outputs 2>/dev/null | sed -n 's/^Output [0-9]* (\(.*\)) is enabled$/\1/p' | grep -Fvx "$MPD_FIFO_OUTPUT" | head -1)"
    if [[ -n "$name" ]]; then
        printf '%s' "$name"
    elif [[ -f "$MPD_OUTPUT_DAT" ]]; then
        printf '%s (saved, mpd not responding)' "$(<"$MPD_OUTPUT_DAT")"
    else
        printf 'unknown'
    fi
}
